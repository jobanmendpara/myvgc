/** A new Team's name, such as "Sleepy Amber Lantern". `random` returns a number in [0, 1). */
export function randomTeamName(random: () => number = Math.random): string {
  return TEAM_NAME_WORDS.map((words) => words[Math.floor(random() * words.length)]).join(' ')
}
